#!/usr/bin/env python3
"""Regenerate ncm_lite/_upstream from vendor/ncm.

The upstream code uses top-level imports (`from models...`, `from utils...`). Those names would collide with
user code, so we copy it into the `ncm_lite._upstream` namespace and rewrite only the import paths.
vendor/ncm stays byte-identical to the official repo; nothing else is changed.
"""
import re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, DST = ROOT / "vendor" / "ncm", ROOT / "ncm_lite" / "_upstream"
PKGS = ("models", "tokenization", "utils")
alt = "|".join(PKGS)
RULES = [
    (re.compile(rf"^(\s*)from ({alt})\.", re.M), r"\1from ncm_lite._upstream.\2."),   # from models.x import y
    (re.compile(rf'"({alt})\.'), r'"ncm_lite._upstream.\1.'),                         # registry strings
]

def main():
    if DST.exists():
        shutil.rmtree(DST)
    for pkg in PKGS:
        for f in (SRC / pkg).glob("*.py"):
            out = DST / pkg / f.name
            out.parent.mkdir(parents=True, exist_ok=True)
            text = f.read_text()
            for rx, rep in RULES:
                text = rx.sub(rep, text)
            out.write_text(text)
    (DST / "__init__.py").write_text('"""Import-rewritten copy of HazyResearch/ncm (MIT). Generated by tools/sync_upstream.py; do not edit."""\n')
    shutil.copy(SRC / "LICENSE", DST / "LICENSE")
    cfgs = ROOT / "ncm_lite" / "configs"
    cfgs.mkdir(exist_ok=True)
    for y in (SRC / "config" / "eval").glob("*.yaml"):
        shutil.copy(y, cfgs / y.name)
    print("synced", sum(1 for _ in DST.rglob("*.py")), "files")

if __name__ == "__main__":
    main()
